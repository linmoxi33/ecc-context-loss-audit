#!/usr/bin/env python3
"""ck-context-loss-audit — predict what `ck migrate` will destroy, before it runs.

The v1->v2 migration in affaan-m/ECC (skills/ck/commands/migrate.mjs, pinned
commit below) parses a hand-written CONTEXT.md with two very narrow regexes and
then OVERWRITES that file in place. This tool ports those exact parsing rules to
Python, re-runs them against your project directory offline, and reports every
line that would disappear, with its source line number.

It does not run ck, does not touch your files, and needs no network.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

TOOL_VERSION = "1.0.0"
UPSTREAM_REPO = "affaan-m/ECC"
UPSTREAM_COMMIT = "3f14a103a8694e51c1df9a806217a6d0b5f7a6f7"
UPSTREAM_FILE = "skills/ck/commands/migrate.mjs"

# Source line numbers in migrate.mjs at UPSTREAM_COMMIT, used in finding text.
EXTRACT_SECTION_LINES = "26-30"
PARSE_BULLETS_LINES = "32-37"
CONTEXT_JSON_LINES = "97-107"
BACKUP_LINES = "178-181"

HEADINGS = [
    "What This Is",
    "Tech Stack",
    "Current Goal",
    "Where I Left Off",
    "Next Steps",
    "Blockers",
    "Do Not Do",
    "Decisions Made",
]
BULLET_SECTIONS = {"Where I Left Off", "Next Steps", "Blockers", "Do Not Do"}

# --- exact ports of migrate.mjs / shared.mjs -------------------------------


def extract_section(md: str, heading: str) -> Optional[str]:
    """migrate.mjs L26-30: new RegExp(`## ${heading}\\n([\\s\\S]*?)(?=\\n## |$)`)."""
    m = re.search(r"## " + re.escape(heading) + r"\n([\s\S]*?)(?=\n## |$)", md)
    return m.group(1).strip() if m else None


def parse_bullets(text: Optional[str]) -> List[str]:
    """migrate.mjs L32-37. The filter needs a single [-*\\d] then whitespace."""
    if not text:
        return []
    out = []
    for line in text.split("\n"):
        t = line.strip()
        if re.match(r"^[-*\d]\s", t):
            t = re.sub(r"^[-*\d]+\.?\s+", "", t).strip()
            if t:
                out.append(t)
    return out


def parse_decisions_table(text: Optional[str]) -> List[Dict[str, str]]:
    rows = []
    if not text:
        return rows
    for line in text.split("\n"):
        if not line.startswith("|") or re.match(r"^[|\s-]+$", line):
            continue
        cols = [c.strip() for c in line.split("|")]
        cols = [c for i, c in enumerate(cols) if 0 < i < 4]
        if cols and not cols[0].startswith("Decision") and not cols[0].startswith("_"):
            rows.append({"what": cols[0], "why": cols[1] if len(cols) > 1 else "",
                         "date": cols[2] if len(cols) > 2 else ""})
    return rows


def parse_left_off(text: Optional[str]) -> List[Dict[str, Optional[str]]]:
    if not text:
        return [{"leftOff": None}]
    blocks = re.split(r"(?=Session \d+)", text)
    if len(blocks) > 1:
        out = []
        for block in blocks:
            if not block.strip():
                continue
            m = re.search(r"\((\d{4}-\d{2}-\d{2})\)", block)
            bullets = parse_bullets(block)
            rest = re.sub(r"^Session \d+.*\n", "", block).strip()
            out.append({"date": m.group(1) if m else None,
                        "leftOff": "\n".join(bullets) if bullets else rest})
        return out
    bullets = parse_bullets(text)
    return [{"leftOff": "\n".join(bullets) if bullets else text.strip()}]


def render_context_md(ctx: Dict[str, Any]) -> str:
    """Port of shared.mjs renderContextMd (layout only; ids/dates come from input)."""
    latest = ctx["sessions"][-1] if ctx.get("sessions") else None
    lines = [
        "<!-- Generated by ck v2 — edit context.json instead -->",
        "# Project: %s" % ctx.get("displayName", ctx["name"]),
        "> Path: %s" % ctx["path"],
    ]
    if ctx.get("repo"):
        lines.append("> Repo: %s" % ctx["repo"])
    lines.append("> Last Session: %s | Sessions: %d" %
                 ((ctx["sessions"][-1].get("date") or "never") if ctx.get("sessions") else "never",
                  len(ctx.get("sessions") or [])))
    lines.append("")
    lines.append("## What This Is")
    lines.append(ctx.get("description") or "_Not set._")
    lines += ["", "## Tech Stack"]
    lines.append(", ".join(ctx["stack"]) if ctx.get("stack") else "_Not set._")
    lines += ["", "## Current Goal"]
    lines.append(ctx.get("goal") or "_Not set._")
    lines += ["", "## Where I Left Off"]
    lines.append((latest or {}).get("leftOff") or "_Not yet recorded. Run /ck:save after your first session._")
    lines += ["", "## Next Steps"]
    ns = (latest or {}).get("nextSteps") or []
    if ns:
        lines += ["%d. %s" % (i + 1, s) for i, s in enumerate(ns)]
    else:
        lines.append("_Not yet recorded._")
    lines += ["", "## Blockers"]
    bl = (latest or {}).get("blockers") or []
    lines += ["- %s" % b for b in bl] if bl else ["- None"]
    lines += ["", "## Do Not Do"]
    cs = ctx.get("constraints") or []
    lines += ["- %s" % c for c in cs] if cs else ["- None specified"]
    lines += ["", "## Decisions Made", "| Decision | Why | Date |", "|----------|-----|------|"]
    all_dec = [dict(d, date=s.get("date")) for s in (ctx.get("sessions") or [])
               for d in (s.get("decisions") or [])]
    if all_dec:
        lines += ["| %s | %s | %s |" % (d["what"], d.get("why", ""), d.get("date", ""))
                  for d in all_dec]
    else:
        lines.append("| _(none yet)_ | | |")
    lines.append("")
    if len(ctx.get("sessions") or []) > 1:
        lines.append("## Session History")
        for s in reversed(ctx["sessions"]):
            lines.append("### %s — %s" % (s.get("date") or "", s.get("summary") or "Session"))
            if s.get("leftOff"):
                lines.append("**Left off:** %s" % s["leftOff"])
        lines.append("")
    return "\n".join(lines)


# --- audit logic ------------------------------------------------------------


@dataclass
class Finding:
    code: str
    severity: str
    message: str
    line: Optional[int] = None
    section: Optional[str] = None
    extra: Dict[str, Any] = field(default_factory=dict)

    def as_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {"code": self.code, "severity": self.severity,
                             "message": self.message}
        if self.line is not None:
            d["line"] = self.line
        if self.section:
            d["section"] = self.section
        d.update(self.extra)
        return d


def _sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def _find_line(text: str, needle: str, start: int = 0) -> Optional[int]:
    idx = text.find(needle, start)
    if idx < 0:
        return None
    return text.count("\n", 0, idx) + 1


def _build_context(meta: Dict[str, Any], name: str, md: str, path: str) -> Dict[str, Any]:
    description = extract_section(md, "What This Is") or extract_section(md, "About")
    stack_raw = extract_section(md, "Tech Stack") or ""
    stack = [re.sub(r"^[-*]\s+", "", s).strip()
             for s in re.split(r"[,\n]", stack_raw) if s.strip()]
    goal_sec = extract_section(md, "Current Goal") or ""
    goal = goal_sec.split("\n")[0].strip() or None
    constraints = parse_bullets(extract_section(md, "Do Not Do") or "")
    decisions = parse_decisions_table(extract_section(md, "Decisions Made") or "")
    next_steps = parse_bullets(extract_section(md, "Next Steps") or "")
    blockers = [b for b in parse_bullets(extract_section(md, "Blockers") or "")
                if b.lower() != "none"]
    left_off = parse_left_off(extract_section(md, "Where I Left Off") or "")
    date = meta.get("lastUpdated") or "1970-01-01"
    sessions = []
    for i, lo in enumerate(left_off):
        last = i == len(left_off) - 1
        sessions.append({
            "id": (meta.get("lastSessionId") or "00000000")[:8] if last else "session%02d" % (i + 1),
            "date": lo.get("date") or date,
            "summary": (meta.get("lastSessionSummary") or "Migrated from v1") if last else
                       "Session %d (migrated)" % (i + 1),
            "leftOff": lo.get("leftOff"),
            "nextSteps": next_steps if last else [],
            "decisions": decisions if last else [],
            "blockers": blockers if last else [],
        })
    return {"version": 2, "name": name, "path": meta.get("path") or path,
            "description": description, "stack": stack, "goal": goal,
            "constraints": constraints, "repo": meta.get("repo"),
            "createdAt": meta.get("lastUpdated") or date, "sessions": sessions,
            "nextSteps": next_steps, "decisions": decisions,
            "blockers": blockers, "constraints_list": constraints}


def audit_project(project_dir: str) -> Dict[str, Any]:
    md_path = os.path.join(project_dir, "CONTEXT.md")
    json_path = os.path.join(project_dir, "context.json")
    meta_path = os.path.join(project_dir, "meta.json")
    findings: List[Finding] = []

    if not os.path.isdir(project_dir):
        raise InputError("project directory not found: %s" % project_dir)
    raw = b""
    md = ""
    if os.path.exists(md_path):
        with open(md_path, "rb") as fh:
            raw = fh.read()
        try:
            md = raw.decode("utf-8")
        except UnicodeDecodeError:
            raise InputError("CONTEXT.md is not valid UTF-8: %s" % md_path)

    meta: Dict[str, Any] = {}
    if os.path.exists(meta_path):
        try:
            with open(meta_path, "r", encoding="utf-8") as fh:
                meta = json.load(fh)
        except (ValueError, OSError):
            findings.append(Finding(
                "META_JSON_UNREADABLE", "warning",
                "meta.json is not valid JSON; migrate.mjs silently continues with "
                "defaults, so path/repo/lastSession metadata is lost too."))
            meta = {}

    existing: Any = None
    mode = "migrate"
    if os.path.exists(json_path):
        try:
            with open(json_path, "r", encoding="utf-8") as fh:
                existing = json.load(fh)
        except (ValueError, OSError):
            existing = None
        if isinstance(existing, dict) and existing.get("version") == 2:
            mode = "skipped"
            findings.append(Finding(
                "ALREADY_V2", "info",
                "context.json declares version 2: migrate.mjs skips this project "
                "entirely (L97-107). No files are rewritten."))
        else:
            findings.append(Finding(
                "CONTEXT_JSON_OVERWRITE", "error",
                "existing context.json is unreadable or not version 2. migrate.mjs "
                "falls through and saveContext() overwrites it; meta.json is backed "
                "up but context.json is not (L97-107, L178-181)."))
    else:
        findings.append(Finding(
            "CONTEXT_JSON_ABSENT", "info",
            "no context.json yet: this is a first migration."))

    crlf = b"\r\n" in raw
    section_present = {h: extract_section(md, h) for h in HEADINGS}
    if crlf:
        wiped = [h for h in HEADINGS if re.search(r"## " + re.escape(h) + r"\S*", md)]
        findings.append(Finding(
            "CRLF_SECTION_WIPE", "error",
            "CONTEXT.md uses CRLF (%d CRLF bytes). extractSection() looks for "
            "'## Heading\\n' and therefore matches none of the %d headings: every "
            "section is written back as a placeholder (_Not set._ / _(none yet)_), "
            "and CONTEXT.md has no backup." % (raw.count(b"\r\n"), len(wiped)),
            extra={"crlf_bytes": raw.count(b"\r\n"), "sections_at_risk": wiped}))

    # Numbered-list data loss, line by line, inside the sections parseBullets reads.
    lines = md.split("\n")
    current = None
    known = {f.code for f in findings}
    for i, line in enumerate(lines, 1):
        m = re.match(r"^## (.+?)\s*$", line)
        if m:
            current = m.group(1).strip()
            continue
        if current in BULLET_SECTIONS and re.match(r"^\s*\d+\.\s+\S", line):
            stripped = line.strip()
            if not re.match(r"^[-*\d]\s", stripped):
                findings.append(Finding(
                    "NUMBERED_STEP_DROPPED", "error",
                    "standard Markdown numbered item is rejected by parseBullets() "
                    "(filter needs one digit or bullet followed by whitespace, L32-37); "
                    "the item disappears from the regenerated file: %r" % stripped,
                    line=i, section=current,
                    extra={"text": stripped, "regex": r"^[-*\d]\s"}))
    if re.search(r"(?m)^\s*\d+\.\s+\S", md) and "NUMBERED_STEP_DROPPED" not in known:
        if not any(f.code == "NUMBERED_STEP_DROPPED" for f in findings):
            findings.append(Finding(
                "NUMBERED_ITEM_OUTSIDE_SECTIONS", "warning",
                "numbered list found outside the four parsed bullet sections; "
                "migrate.mjs never reads that region, so it is dropped regardless "
                "of its formatting."))

    # Generic coverage proof: compare real content lines with the predicted output.
    ctx = _build_context(meta, os.path.basename(os.path.normpath(project_dir)), md,
                         meta.get("path") or project_dir)
    predicted_md = render_context_md(ctx) if mode == "migrate" else md
    def norm(x: str) -> str:
        x = re.sub(r"^[-*]\s+", "", x.strip())
        return re.sub(r"\s+", " ", x)

    pred_norm = [norm(l) for l in predicted_md.split("\n") if norm(l)]
    content_total = 0
    lost: List[Dict[str, Any]] = []
    for i, line in enumerate(lines, 1):
        s = line.strip()
        if (not s or s.startswith("#") or s.startswith("<!--")
                or s.startswith(">") or re.match(r"^[|\s:-]+$", s)):
            continue
        content_total += 1
        ns = norm(s)
        if s.startswith("|") and s.count("|") >= 3:
            cells = [c.strip() for c in s.split("|")[1:-1]]
            ns = "| " + " | ".join(cells[:2]) + " |"
        if mode == "migrate" and not any(ns in pn for pn in pred_norm):
            lost.append({"line": i, "text": s, "section": current})
    explained = {(f.line, (f.extra or {}).get("text")) for f in findings
                 if f.code == "NUMBERED_STEP_DROPPED"}
    unexplained = [x for x in lost if (x["line"], x["text"]) not in explained]
    if mode == "migrate" and not crlf:
        for x in unexplained[:30]:
            findings.append(Finding(
                "CONTENT_LINE_LOST", "error",
                "line does not survive the v2 render (byte-for-byte check against "
                "the ported renderer): %r" % x["text"],
                line=x["line"], section=x["section"], extra={"text": x["text"]}))

    if mode == "migrate" and not os.path.exists(md_path + ".v1-backup"):
        findings.append(Finding(
            "CONTEXT_MD_NO_BACKUP", "warning",
            "migrate.mjs renames only meta.json to meta.json.v1-backup (L178-181); "
            "the original CONTEXT.md is overwritten with no rollback copy."))

    src_dates = []
    for line in (extract_section(md, "Decisions Made") or "").split("\n"):
        if line.startswith("|") and line.count("|") >= 3:
            cells = [c.strip() for c in line.split("|")[1:-1]]
            if cells and cells[0] and not cells[0].startswith(("Decision", "_", "-")):
                src_dates.append(cells[2] if len(cells) > 2 else "")
    sess_date = (ctx["sessions"][-1].get("date") if ctx["sessions"] else None) or ""
    rewritten = [d for d in src_dates if d and d != sess_date]
    if mode == "migrate" and rewritten:
        findings.append(Finding(
            "DECISION_DATE_REWRITTEN", "warning",
            "%d decision row(s) carry their own date, but the renderer overwrites the "
            "Date column with the session date (%s): %s" %
            (len(rewritten), sess_date, ", ".join(sorted(set(rewritten))))))
    preserved = content_total - len(lost) if content_total else 0
    return {
        "tool": "ck-context-loss-audit",
        "version": TOOL_VERSION,
        "upstream": {"repo": UPSTREAM_REPO, "pinned_commit": UPSTREAM_COMMIT,
                     "file": UPSTREAM_FILE,
                     "source_lines": {"extractSection": EXTRACT_SECTION_LINES,
                                      "parseBullets": PARSE_BULLETS_LINES,
                                      "context_json": CONTEXT_JSON_LINES,
                                      "backup": BACKUP_LINES}},
        "project": os.path.abspath(project_dir),
        "mode": mode,
        "input_sha256": _sha256_bytes(raw),
        "predicted": {
            "sections": {h: (v is not None) for h, v in section_present.items()},
            "next_steps": ctx["nextSteps"],
            "constraints": ctx["constraints"],
            "decisions": len(ctx["decisions"]),
            "content_lines": content_total,
            "content_lines_preserved": preserved,
            "lost_lines": lost,
            "predicted_markdown_sha256": _sha256_bytes(predicted_md.encode("utf-8")),
        },
        "findings": [f.as_dict() for f in findings],
        "summary": {
            "errors": sum(1 for f in findings if f.severity == "error"),
            "warnings": sum(1 for f in findings if f.severity == "warning"),
            "infos": sum(1 for f in findings if f.severity == "info"),
        },
        "predicted_markdown": predicted_md if mode == "migrate" else None,
    }


def audit_memory_dir(memory_dir: str) -> List[Finding]:
    """Issue #4017: unquoted colon-space in YAML frontmatter makes it unreadable."""
    out: List[Finding] = []
    if not os.path.isdir(memory_dir):
        raise InputError("memory directory not found: %s" % memory_dir)
    for name in sorted(os.listdir(memory_dir)):
        if not (name.startswith("ck_") and name.endswith(".md")):
            continue
        p = os.path.join(memory_dir, name)
        try:
            with open(p, "r", encoding="utf-8") as fh:
                text = fh.read()
        except OSError as exc:
            out.append(Finding("MEMORY_UNREADABLE", "warning", "cannot read %s: %s" % (name, exc)))
            continue
        if not text.startswith("---\n"):
            continue
        end = text.find("\n---", 4)
        if end < 0:
            continue
        fm = text[4:end]
        for i, line in enumerate(fm.split("\n"), 2):
            m = re.match(r"^name:\s*(.*)$", line)
            if not m:
                continue
            value = m.group(1)
            if value.startswith(("'", '"')):
                continue
            if ": " in value or " #" in value:
                out.append(Finding(
                    "MEMORY_FRONTMATTER_INVALID", "error",
                    "unquoted YAML scalar contains %r; js-yaml reads this as a nested "
                    "mapping and fails with 'bad indentation of a mapping entry': %r"
                    % (": " if ": " in value else " #", line),
                    line=i, extra={"file": name, "value": value}))
    return out


class InputError(Exception):
    pass


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        prog="ck-context-loss-audit",
        description="Predict what affaan-m/ECC's `ck migrate` will delete from CONTEXT.md.")
    ap.add_argument("project_dir", help="directory holding CONTEXT.md / context.json / meta.json")
    ap.add_argument("--memory-dir", help="optional memory/ directory of ck_*.md summaries")
    ap.add_argument("--json", action="store_true", help="emit one JSON object on stdout")
    ap.add_argument("--write-predicted", metavar="FILE",
                    help="write the predicted post-migration CONTEXT.md to FILE")
    ap.add_argument("--quiet", action="store_true", help="suppress the text report")
    args = ap.parse_args(argv)

    try:
        report = audit_project(args.project_dir)
        if args.memory_dir:
            mem = audit_memory_dir(args.memory_dir)
            report["findings"].extend(f.as_dict() for f in mem)
            report["summary"] = {
                "errors": sum(1 for f in report["findings"] if f["severity"] == "error"),
                "warnings": sum(1 for f in report["findings"] if f["severity"] == "warning"),
                "infos": sum(1 for f in report["findings"] if f["severity"] == "info"),
            }
    except InputError as exc:
        sys.stderr.write("ck-context-loss-audit: %s\n" % exc)
        return 2

    if args.write_predicted:
        md = report.get("predicted_markdown")
        if md is None:
            sys.stderr.write("ck-context-loss-audit: project is already v2; nothing to predict\n")
            return 2
        with open(args.write_predicted, "w", encoding="utf-8") as fh:
            fh.write(md)
    report.pop("predicted_markdown", None)

    if args.json:
        json.dump(report, sys.stdout, ensure_ascii=False, indent=2)
        sys.stdout.write("\n")
    elif not args.quiet:
        print("ck-context-loss-audit %s  mode=%s  sha256=%s" %
              (TOOL_VERSION, report["mode"], report["input_sha256"][:16]))
        for f in report["findings"]:
            loc = " line %s" % f["line"] if "line" in f else ""
            sec = " [%s]" % f["section"] if "section" in f else ""
            print("%-7s %-28s%s%s  %s" % (f["severity"].upper(), f["code"], loc, sec,
                                          f["message"]))
        p = report["predicted"]
        print("content lines: %d, preserved in prediction: %d, lost: %d" %
              (p["content_lines"], p["content_lines_preserved"], len(p["lost_lines"])))
    return 1 if report["summary"]["errors"] else 0


if __name__ == "__main__":
    sys.exit(main())